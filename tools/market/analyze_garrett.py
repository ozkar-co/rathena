#!/usr/bin/env python3
"""Compare the legacy Garrett arrays against the v2 canonical market data.

Reads the hardcoded arrays in npc/custom/ozro/trasher.txt and writes a
reproducible comparison. This is an analysis tool, not an NPC generator.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from market import build_sample, common  # noqa: E402

TRASHER = common.ROOT / "npc" / "custom" / "ozro" / "trasher.txt"
OUT_DIR = common.ROOT / "data" / "market" / "samples"
ARRAY_RE = re.compile(r"setarray\s+\.(\w+)\[0\]\s*,\s*([^;]+);")


def parse_arrays() -> dict[str, list[int]]:
    text = TRASHER.read_text(encoding="latin-1", errors="replace")
    arrays: dict[str, list[int]] = {}
    for name, raw in ARRAY_RE.findall(text):
        arrays[name] = [int(value) for value in re.findall(r"-?\d+", raw)]
    return arrays


def main() -> None:
    arrays = parse_arrays()
    data = build_sample.load_inputs()
    metrics = build_sample.build_metrics(data)
    build_sample.build_prices(data, metrics)
    build_sample.apply_craft_costs(metrics)

    offers = []
    for tier in ("abundant", "common", "uncommon", "rare"):
        ids = arrays.get(f"{tier}_id") or []
        prices = arrays.get(f"{tier}_price") or []
        for item_id, old_price in zip(ids, prices):
            metric = metrics.get(item_id)
            if not metric:
                continue
            offers.append(
                {
                    "tier": tier,
                    "itemId": item_id,
                    "name": metric["name"],
                    "oldPrice": old_price,
                    "canonicalBuy": metric["price"]["npcBuyPrice"],
                    "canonicalMid": metric["price"]["mid"],
                    "canonicalSell": metric["price"]["npcSellPrice"],
                    "oldVsBuy": round(old_price / max(1, metric["price"]["npcBuyPrice"]), 3),
                    "status": metric["price"]["status"],
                    "abundance": metric["abundanceTier"],
                    "supplyOpen": round(metric["supplyOpen"], 3),
                }
            )

    missions = []
    for tier in ("mcommon", "muncommon", "mrare"):
        ids = arrays.get(f"{tier}_id") or []
        quantities = arrays.get(f"{tier}_qty") or []
        payouts = arrays.get(f"{tier}_pay") or []
        for item_id, quantity, old_payout in zip(ids, quantities, payouts):
            metric = metrics.get(item_id)
            if not metric:
                continue
            buy = metric["price"]["npcBuyPrice"]
            mid = metric["price"]["mid"]
            missions.append(
                {
                    "tier": tier,
                    "itemId": item_id,
                    "name": metric["name"],
                    "quantity": quantity,
                    "oldPayout": old_payout,
                    "canonicalBuyValue": buy * quantity,
                    "canonicalMidValue": mid * quantity,
                    "oldVsBuy": round(old_payout / max(1, buy * quantity), 3),
                    "status": metric["price"]["status"],
                    "abundance": metric["abundanceTier"],
                    "supplyOpen": round(metric["supplyOpen"], 3),
                    "difficulty": metric["difficultyTier"],
                }
            )

    out = {
        "schemaVersion": 1,
        "source": str(TRASHER.relative_to(common.ROOT)),
        "offers": sorted(offers, key=lambda row: row["oldVsBuy"], reverse=True),
        "missions": sorted(missions, key=lambda row: row["oldVsBuy"], reverse=True),
    }
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "garrett_comparison.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    lines = [
        "# Garrett legacy vs market v2",
        "",
        "Generated by `tools/market/analyze_garrett.py`.",
        "",
        "## Offers",
        "",
        "| Item | Old | Canonical buy | Ratio | Tier | Status |",
        "|---|---:|---:|---:|---|---|",
    ]
    for row in out["offers"]:
        lines.append(
            f"| {row['name']} | {row['oldPrice']:,} | {row['canonicalBuy']:,} | "
            f"{row['oldVsBuy']:.2f}x | {row['abundance']} | {row['status']} |"
        )
    lines += [
        "",
        "## Missions",
        "",
        "| Item | Qty | Old payout | Buy × qty | Ratio | Tier | Status |",
        "|---|---:|---:|---:|---:|---|---|",
    ]
    for row in out["missions"]:
        lines.append(
            f"| {row['name']} | {row['quantity']} | {row['oldPayout']:,} | "
            f"{row['canonicalBuyValue']:,} | {row['oldVsBuy']:.2f}x | {row['abundance']} | {row['status']} |"
        )
    (OUT_DIR / "garrett_comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"wrote {OUT_DIR / 'garrett_comparison.json'}")
    print(f"offers={len(offers)} missions={len(missions)}")


if __name__ == "__main__":
    main()
